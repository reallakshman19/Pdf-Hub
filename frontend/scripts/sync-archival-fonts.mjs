#!/usr/bin/env node
/**
 * Generates compressed redistributable archival font assets (OFL Liberation Sans TTF
 * + BSD-3 PDFium Foxit Type 1 PFB) from installed `pdfjs-dist/standard_fonts` into
 * `src/core/pdfa/assets/archivalFontBundle.ts` for lazy worker/browser loading.
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.resolve(__dirname, '..');
const sourceDir = path.join(frontendRoot, 'node_modules', 'pdfjs-dist', 'standard_fonts');
const outputFile = path.join(frontendRoot, 'src', 'core', 'pdfa', 'assets', 'archivalFontBundle.ts');

const FONT_ENTRIES = [
  { key: 'sansRegular', file: 'LiberationSans-Regular.ttf', kind: 'ttf' },
  { key: 'sansBold', file: 'LiberationSans-Bold.ttf', kind: 'ttf' },
  { key: 'sansItalic', file: 'LiberationSans-Italic.ttf', kind: 'ttf' },
  { key: 'sansBoldItalic', file: 'LiberationSans-BoldItalic.ttf', kind: 'ttf' },
  { key: 'serifRegular', file: 'FoxitSerif.pfb', kind: 'pfb' },
  { key: 'serifBold', file: 'FoxitSerifBold.pfb', kind: 'pfb' },
  { key: 'serifItalic', file: 'FoxitSerifItalic.pfb', kind: 'pfb' },
  { key: 'serifBoldItalic', file: 'FoxitSerifBoldItalic.pfb', kind: 'pfb' },
  { key: 'fixedRegular', file: 'FoxitFixed.pfb', kind: 'pfb' },
  { key: 'fixedBold', file: 'FoxitFixedBold.pfb', kind: 'pfb' },
  { key: 'fixedItalic', file: 'FoxitFixedItalic.pfb', kind: 'pfb' },
  { key: 'fixedBoldItalic', file: 'FoxitFixedBoldItalic.pfb', kind: 'pfb' },
  { key: 'symbol', file: 'FoxitSymbol.pfb', kind: 'pfb' },
  { key: 'dingbats', file: 'FoxitDingbats.pfb', kind: 'pfb' },
];

function wrapBase64Array(b64, width = 100) {
  const lines = [];
  for (let i = 0; i < b64.length; i += width) {
    lines.push(`    '${b64.slice(i, i + width)}'`);
  }
  return `[\n${lines.join(',\n')},\n  ].join('')`;
}

const payloadLines = [];
for (const entry of FONT_ENTRIES) {
  const fullPath = path.join(sourceDir, entry.file);
  if (!fs.existsSync(fullPath)) {
    throw new Error(`Missing source font asset: ${fullPath}`);
  }
  const raw = fs.readFileSync(fullPath);
  const compressed = zlib.deflateSync(raw, { level: 9 });
  const b64 = compressed.toString('base64');
  payloadLines.push(`  // ${entry.file} (raw ${raw.length} B, zlib ${compressed.length} B)`);
  payloadLines.push(`  ${entry.key}: ${wrapBase64Array(b64)},`);
}

const output = `/**
 * Auto-generated by scripts/sync-archival-fonts.mjs — DO NOT EDIT BY HAND.
 * Licenses: LiberationSans-*.ttf (SIL OFL 1.1); Foxit*.pfb (BSD 3-Clause PDFium).
 * Lazy-imported only when archival font remediation or PDF/A export runs.
 */
import { unzlibSync } from 'fflate';

export type ArchivalFontAssetKey =
  | 'sansRegular'
  | 'sansBold'
  | 'sansItalic'
  | 'sansBoldItalic'
  | 'serifRegular'
  | 'serifBold'
  | 'serifItalic'
  | 'serifBoldItalic'
  | 'fixedRegular'
  | 'fixedBold'
  | 'fixedItalic'
  | 'fixedBoldItalic'
  | 'symbol'
  | 'dingbats';

const COMPRESSED_FONTS: Record<ArchivalFontAssetKey, string> = {
${payloadLines.join('\n')}
};

const decodedCache = new Map<ArchivalFontAssetKey, Uint8Array>();

function decodeBase64(b64: string): Uint8Array {
  const binary = globalThis.atob(b64);
  const out = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i += 1) {
    out[i] = binary.charCodeAt(i);
  }
  return out;
}

export function loadArchivalFontAsset(key: ArchivalFontAssetKey): Uint8Array {
  const cached = decodedCache.get(key);
  if (cached) {
    return cached;
  }
  const inflated = unzlibSync(decodeBase64(COMPRESSED_FONTS[key]));
  decodedCache.set(key, inflated);
  return inflated;
}
`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, output, 'utf8');
console.log(`Generated ${path.relative(frontendRoot, outputFile)} (${FONT_ENTRIES.length} archival font assets).`);
